// Integration tests exercise real Word/PDF extraction and LibreOffice conversion.
const assert=require('node:assert/strict'),fs=require('fs'),path=require('path');
const {spawnSync}=require('child_process');
const {extractDesign,readDocx}=require('../kit/extract_design_lib');
const {inspectPdf}=require('../kit/pdf_checks');
const root=path.resolve(__dirname,'..'),dir=path.join(root,'work','design-tests');
fs.mkdirSync(dir,{recursive:true});
const cfgLib=require('../kit/config');
const basePath=cfgLib.BASE,base=JSON.parse(fs.readFileSync(basePath,'utf8'));
const resumeFile=cfgLib.fileName(cfgLib.load().outputFileName,base.name);
const run=(args,env={})=>{const r=spawnSync(process.execPath,args,{cwd:root,encoding:'utf8',env:{...process.env,...env},timeout:180000});if(r.status!==0)throw new Error(r.stdout+'\n'+r.stderr);return r.stdout+r.stderr;};
(async()=>{
  const fixture=JSON.parse(fs.readFileSync(path.join(root,'kit/design_defaults.json'),'utf8'));
  fixture.fonts={primary:'Arial',fallback:'Arial',allowedFamilies:['Arial','Georgia']};
  fixture.elements.name={...fixture.elements.name,font:'Georgia',size:{pt:22,halfPoints:44},alignment:'left',color:'336699',border:null};
  fixture.elements.sectionHeading.color='336699';
  fixture.elements.experienceBullet.spacing={before:0,after:0};
  fixture.margins.normal={top:720,bottom:720,left:800,right:800};
  fixture.sectionOrder=['header','professionalSummary','technicalSkills','education','professionalExperience','extraSections','certifications'];
  const fixturePath=path.join(dir,'fixture-design.json'),sourceDocx=path.join(dir,'reference.docx');
  fs.writeFileSync(fixturePath,JSON.stringify(fixture));
  run(['kit/build_resume.js',basePath,sourceDocx],{RESUME_DESIGN:fixturePath});
  const extracted=await extractDesign(sourceDocx,base);
  assert.equal(extracted.spec.elements.name.font,'Georgia');
  assert.equal(extracted.spec.elements.name.alignment,'left');
  assert.equal(extracted.spec.elements.name.border,null);
  assert.equal(extracted.spec.elements.name.color,'336699');
  assert.equal(extracted.spec.elements.experienceBullet.spacing.after,0);
  assert.equal(extracted.spec.elements.skillRow.labelWeight,'bold');
  assert.equal(extracted.spec.elements.skillRow.itemsWeight,'regular');
  assert(extracted.spec.elements.skillRow.bullet);
  assert.deepEqual(extracted.spec.margins.normal,fixture.margins.normal);
  assert(extracted.spec.sectionOrder.indexOf('education')<extracted.spec.sectionOrder.indexOf('professionalExperience'));
  const specPath=path.join(dir,'extracted-design.json');fs.writeFileSync(specPath,JSON.stringify(extracted.spec));
  const env={RESUME_DESIGN:specPath,RESUME_ROOT:path.join(dir,'output')};
  console.log(run(['kit/make_resume.js',basePath,'Roundtrip','--pages','2'],env));
  const pdf=path.join(env.RESUME_ROOT,'Roundtrip',resumeFile);
  const check=await inspectPdf(pdf,extracted.spec,[base.name,'Technical Skills','Education']);
  assert(check.fonts.some(f=>/^Georgia/.test(f)));assert(check.fonts.some(f=>/^Arial/.test(f)));
  const fromPdf=await extractDesign(pdf,base);
  assert.equal(fromPdf.spec.elements.name.font,'Georgia');
  assert.equal(fromPdf.spec.elements.name.color,'336699');
  assert(fromPdf.spec.fonts.allowedFamilies.includes('Arial'));
  const roundtripDocx=path.join(dir,'roundtrip.docx');run(['kit/build_resume.js',basePath,roundtripDocx],env);
  const roundtrip=await readDocx(roundtripDocx);
  assert.equal(roundtrip.paras.find(p=>p.text===base.name).style.font,'Georgia');
  await assert.rejects(()=>extractDesign(sourceDocx,{...base,name:'Wrong Name'}),/name does not match/);
  // A missing font must fail validation instead of silently accepting replacement.
  await assert.rejects(()=>inspectPdf(pdf,{fonts:{primary:'MissingFont',allowedFamilies:['MissingFont']}}),/substituted/);
  // Exercise shared header rows and right-aligned job fields independently of font availability.
  const inline=structuredClone(extracted.spec);inline.inlineDates=true;inline.inlineJobLocation=true;
  inline.elements.jobLocation=inline.elements.locationLine;
  inline.jobOrder=['jobTitle','datesLine','companyName','keyProjectsLine'];
  inline.contactOrder=['phone','email'];
  inline.headerRows=[{keys:['name']},{keys:['titleLine']},{keys:['contactLine','locationLine','linksLine']}];
  const inlinePath=path.join(dir,'inline-design.json'),inlineDocx=path.join(dir,'inline.docx');fs.writeFileSync(inlinePath,JSON.stringify(inline));
  const inlineData=structuredClone(base);for(const j of inlineData.jobs)j.location=j.location||'Example City';
  const inlineJson=path.join(dir,'inline-resume.json');fs.writeFileSync(inlineJson,JSON.stringify(inlineData));
  run(['kit/build_resume.js',inlineJson,inlineDocx],{RESUME_DESIGN:inlinePath});
  const inlineRead=await readDocx(inlineDocx);
  assert(inlineRead.paras.some(p=>p.text.includes(base.jobs[0].title)&&p.text.includes(base.jobs[0].dates)));
  assert(inlineRead.paras.some(p=>p.text.includes(base.jobs[0].company)&&p.text.includes(inlineData.jobs[0].location)));
  assert(inlineRead.paras.some(p=>p.text.includes(base.email)&&p.text.includes(base.location)));
  const invalid=spawnSync(process.execPath,['kit/extract_design.js','resume/base_resume.json',path.join(dir,'invalid.json')],{cwd:root,encoding:'utf8'});
  assert.notEqual(invalid.status,0);assert(!fs.existsSync(path.join(dir,'invalid.json')));
  const cover=path.join(dir,'cover.json');fs.writeFileSync(cover,JSON.stringify({paragraphs:['I am applying for a frontend engineering role.','My experience includes enterprise applications.','I bring Angular and TypeScript experience.','Thank you for your consideration.']}));
  console.log(run(['kit/make_cover_letter.js',cover,'Roundtrip'],env));
  console.log('PASS: DOCX properties, PDF font/color extraction, section order, zero spacing, no border, reference margins, missing-font rejection, wrong-reference rejection, JSON rejection, resume and cover-letter PDFs.');
})().catch(e=>{console.error(e);process.exitCode=1;});
