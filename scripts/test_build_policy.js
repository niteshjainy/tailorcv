const assert=require('node:assert/strict'),fs=require('fs'),path=require('path');
const {spawnSync}=require('child_process');
const {prepareFonts,downloadFont,installedFonts}=require('../kit/font_manager');
const {pageDecision}=require('../kit/page_policy');
const {inspectPdf}=require('../kit/pdf_checks');
const root=path.resolve(__dirname,'..'),dir=path.join(root,'work','policy-tests');fs.mkdirSync(dir,{recursive:true});
const cfgLib=require('../kit/config'),basePath=cfgLib.BASE,base=JSON.parse(fs.readFileSync(basePath,'utf8'));
const resumeFile=cfgLib.fileName(cfgLib.load().outputFileName,base.name);
const cfg={maxPages:'auto',fallbackFont:'Calibri',downloadFonts:true};
const spec=JSON.parse(fs.readFileSync(path.join(root,'kit/design_defaults.json'),'utf8'));spec.source={pageCount:1};
const check=(args,env,expected=0)=>{const r=spawnSync(process.execPath,args,{cwd:root,env:{...process.env,...env},encoding:'utf8',timeout:180000});console.log(r.stdout);assert.equal(r.status,expected,r.stderr);return r;};
(async()=>{
  assert.equal(pageDecision(cfg,spec,1).status,'accepted');
  assert.equal(pageDecision(cfg,spec,2).status,'choice_required');
  assert.equal(pageDecision(cfg,spec,2,'1').status,'shorten_required');
  assert.equal(pageDecision(cfg,spec,2,'2').status,'accepted');
  assert.equal(pageDecision(cfg,{source:{pageCount:2}},3).status,'shorten_required');
  assert.throws(()=>pageDecision(cfg,spec,2,'3'),/--pages/);
  const missing=structuredClone(spec);missing.fonts.primary='Unavailable Test Font';missing.elements.name.font='Unavailable Test Font';
  let attempted=false;
  const fallback=await prepareFonts(missing,cfg,{installed:['Calibri'],fetcher:async()=>{attempted=true;return {ok:false,status:404};},cache:path.join(dir,'missing-fonts')});
  assert(attempted);assert.equal(fallback.spec.fonts.primary,'Calibri');assert.equal(missing.fonts.primary,'Unavailable Test Font');assert(fallback.messages.some(s=>s.includes('→ Calibri')));
  await assert.rejects(()=>downloadFont('Unlicensed Test Font',path.join(dir,'bad-fonts'),async()=>new Response('No permission supplied',{status:200})),/No verified OFL/);
  const embedded=structuredClone(spec);embedded.fonts={primary:'Lato',fallback:'Lato',allowedFamilies:['Lato']};
  for(const element of Object.values(embedded.elements))element.font='Lato';
  const resolved=await prepareFonts(embedded,cfg,{installed:installedFonts().filter(f=>f!=='Lato')});
  assert(resolved.spec.embeddedFonts.length===1);assert(resolved.messages.some(m=>m.includes('embedded locally')));
  const effective=path.join(dir,'lato-design.json');fs.writeFileSync(effective,JSON.stringify(resolved.spec));
  const env={RESUME_DESIGN:effective,RESUME_ROOT:path.join(dir,'output')};
  check(['kit/make_resume.js',basePath,'Embedded Font','--pages','2'],env);
  const pdf=path.join(env.RESUME_ROOT,'Embedded Font',resumeFile);
  const inspection=await inspectPdf(pdf,{fonts:{primary:'Lato',allowedFamilies:['Lato']}},[base.name]);
  assert(inspection.fonts.some(f=>f.startsWith('Lato')),'LibreOffice must actually use the downloaded embedded font');
  // The same real document must require a choice before saving beyond its master limit.
  check(['kit/make_resume.js',basePath,'Pending Page Choice'],env,10);
  assert(!fs.existsSync(path.join(env.RESUME_ROOT,'Pending Page Choice',resumeFile)));
  const request=JSON.parse(fs.readFileSync(path.join(root,'work','Pending_Page_Choice_page_choice.json'),'utf8'));
  assert.equal(request.status,'choice_required');assert.equal(request.options[0].pages,1);assert.equal(request.options[1].pages,2);assert(fs.existsSync(request.preview));
  console.log('PASS: auto page limits, explicit page choices, pending-review PDF, no silent expansion, download license rejection, disclosed fallback, master design preserved, licensed local cache and real LibreOffice font embedding.');
})().catch(e=>{console.error(e);process.exitCode=1;});
